/**
 * Assignment Operators
 * Used to assign values to variables.
 */

let x = 10;
console.log("--- Assignment Operators ---");
console.log("Initial x:", x);

x += 5; // x = x + 5
console.log("x += 5:", x); // 15

x -= 3; // x = x - 3
console.log("x -= 3:", x); // 12

x *= 2; // x = x * 2
console.log("x *= 2:", x); // 24

x /= 4; // x = x / 4
console.log("x /= 4:", x); // 6

x %= 4; // x = x % 4
console.log("x %= 4:", x); // 2

x **= 3; // x = x ** 3
console.log("x **= 3:", x); // 8 (2^3)
